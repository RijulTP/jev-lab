"""Step-timeline components for the Chat 'What just happened' panel."""
from __future__ import annotations

import streamlit as st

from ui.components import prob_bars


def step_build_state(state: dict, tokens: int, beginner: bool):
    st.markdown("**1 · Build the state**")
    if beginner:
        st.caption(f"Send the latest message plus last {len(state.get('history', []))} turns and the shop policy ({tokens} tokens).")
    with st.expander("State JSON", expanded=not beginner):
        st.code(__import__("json").dumps(state, indent=2)[:2000], language="json")


def step_ask(latency_ms: float, in_tok: int, cost_usd: float, cum_usd: float, beginner: bool):
    st.markdown("**2 · Ask Jev, once**")
    st.write(f"6 questions, 1 call — {latency_ms:.0f} ms, {in_tok} tokens (~${cost_usd:.4f}, total ~${cum_usd:.4f}).")
    if beginner:
        st.caption("One call answers everything; extra questions barely change the time.")


def step_answers(answers: dict, beginner: bool):
    st.markdown("**3 · Read the answers**")
    for name, ans in answers.items():
        st.subheader(name)
        prob_bars(ans)


def step_rules(decision, beginner: bool):
    st.markdown("**4 · Apply our rules**")
    for t in decision.trace:
        mark = "✓" if t.fired else "✗"
        if t.fired:
            st.success(f"{mark} {t.rule}: {t.reason}")
        elif not beginner:
            st.caption(f"{mark} {t.rule}: {t.reason}")
    if beginner:
        st.caption(f"Fired rule: {decision.firing_rule}. {decision.note}")


def step_reply(template_name: str, text: str):
    st.markdown("**5 · Send a reply**")
    st.info(f"template: {template_name}")
    st.write(text)
    st.caption("No text was generated by Jev — canned template only.")
