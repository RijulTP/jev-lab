"""Pure routing policy: Jev answers + thresholds -> (action, firing rule, trace).

No API calls, no imports of client/cache/budget. First match wins.
Frozen defaults (tune only via sliders; changes post-record get README line):
  override P>=0.75 refuse; safety P>=0.50 urgent handoff; asks_human P>=0.60 handoff;
  intent confidence<0.50 clarify; intent==other out-of-scope; urgency|frustration>=2.5 priority.
"""

from __future__ import annotations

from dataclasses import dataclass, field

DEFAULTS = {
    "override_yes": 0.75,
    "safety_yes": 0.50,
    "human_yes": 0.60,
    "intent_conf_lo": 0.50,
    "priority_score": 2.5,
}

# Template names must exist in data/templates.yaml.
T_INTENT = {
    "order_status": "order_status",
    "refund_request": "refund_policy",
    "technical_issue": "technical_help",
    "account_access": "account_help",
    "product_question": "product_info",
    "complaint": "complaint_ack",
    "other": "out_of_scope",
}


@dataclass
class RuleTrace:
    rule: str
    fired: bool
    reason: str


@dataclass
class Decision:
    action: str  # refuse | urgent_handoff | handoff | clarify | reply
    template: str
    firing_rule: str
    trace: list = field(default_factory=list)
    note: str = ""


def _noul(answers: dict, name: str) -> float:
    return float((answers.get(name) or {}).get("noul", 0.0))


def _choice(answers: dict, name: str) -> tuple[str, float]:
    a = answers.get(name) or {}
    return str(a.get("choice", "other")), float(a.get("confidence", 0.0))


def _score(answers: dict, name: str) -> float:
    return float((answers.get(name) or {}).get("score", 0.0))


def decide(answers: dict, thresholds: dict | None = None) -> Decision:
    t = {**DEFAULTS, **(thresholds or {})}
    trace: list[RuleTrace] = []

    def check(rule: str, fired: bool, reason: str) -> bool:
        trace.append(RuleTrace(rule, fired, reason))
        return fired

    p_over = _noul(answers, "override_attempt")
    if check("override_refuse", p_over >= t["override_yes"],
             f"override P={p_over:.2f} vs {t['override_yes']:.2f}"):
        return Decision("refuse", "refuse_override", "override_refuse", trace,
                        "Detected instruction-override phrasing; canned refusal, no action taken.")

    p_safe = _noul(answers, "safety_risk")
    if check("safety_handoff", p_safe >= t["safety_yes"],
             f"safety P={p_safe:.2f} vs {t['safety_yes']:.2f} (lower bar: misses cost more)"):
        return Decision("urgent_handoff", "priority_handoff", "safety_handoff", trace,
                        "Priority handoff to a human queue. Demo only — real emergency: contact local services.")

    p_human = _noul(answers, "asks_human")
    if check("human_request", p_human >= t["human_yes"],
             f"asks_human P={p_human:.2f} vs {t['human_yes']:.2f}"):
        return Decision("handoff", "human_handoff", "human_request", trace,
                        "Customer asked for a human.")

    intent, conf = _choice(answers, "intent")
    if check("low_confidence", conf < t["intent_conf_lo"],
             f"intent={intent} conf={conf:.2f} vs {t['intent_conf_lo']:.2f}"):
        return Decision("clarify", "clarify", "low_confidence", trace,
                        "Not sure enough to act — ask one clarifying question.")

    if check("out_of_scope", intent == "other", f"intent={intent}"):
        return Decision("reply", "out_of_scope", "out_of_scope", trace,
                        "Out-of-scope reply; canned template.")

    urg, fru = _score(answers, "urgency"), _score(answers, "frustration")
    if check("priority", urg >= t["priority_score"] or fru >= t["priority_score"],
             f"urgency={urg:.2f} frustration={fru:.2f} vs {t['priority_score']:.2f}"):
        return Decision("urgent_handoff", "priority_handoff", "priority", trace,
                        "High urgency/frustration — priority handoff with empathetic note.")

    check("intent_template", True, f"intent={intent} -> template {T_INTENT.get(intent, 'out_of_scope')}")
    return Decision("reply", T_INTENT.get(intent, "out_of_scope"), "intent_template", trace,
                    f"Template reply for intent {intent}. Jev judged; no text generated by Jev.")
